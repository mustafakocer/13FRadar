const I18nCtx = createContext(null);

// The site is Turkish-only; the language still rides in the URL (/tr/…) and
// is passed in by the entry point so server and client render the same text.
export function I18nProvider({ lang = 'tr', children }) {
  const t = useCallback((key) => dict.tr[key] ?? key, []);
  const value = useMemo(() => ({ lang, t }), [lang, t]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
